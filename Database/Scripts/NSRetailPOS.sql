		FROM #BUYOFFERS BO
		WHERE BO.ISBUYITEMS = 1

		UPDATE BO
		SET BO.FREEQTY = @FreeItemQuantity, BO.SALEPRICEQTY = BO.BUYQTY - @FreeItemQuantity
		FROM #BUYOFFERS BO
		WHERE BO.ISBUYITEMS = 0

		UPDATE PBD
