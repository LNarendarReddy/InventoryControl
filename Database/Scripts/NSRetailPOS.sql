CREATE   PROCEDURE [dbo].[POS_USP_RECALCULATE_OFFER1010]
    @BillID INT,
    @DealID INT,
    @BillDetailID INT = NULL,
    @Quantity INT = NULL,
    @QuantityOrWeightMultiplier DECIMAL(7, 2) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @BuyQuantity INT,
        @FreeQuantity INT,
        @DealQuantity INT,
        @DealAppliesToID INT,
        @TotalEligibleQuantity INT,
        @CompleteDeals INT,
        @PaidQuantity INT,
        @FreeQuantityToAllocate INT,
        @SalePriceQuantityToAllocate INT

    SELECT
        @BuyQuantity = OFR.NUMBEROFITEMS,
        @FreeQuantity = OFR.NUMBEROFFREEITEMS
    FROM POS_OFFER OFR
    WHERE OFR.OFFERID = @DealID
        AND OFR.OFFERTYPEID = 1010

    IF ISNULL(@BuyQuantity, 0) <= 0 OR ISNULL(@FreeQuantity, 0) <= 0
    BEGIN
        RAISERROR('BUY N GET N deal requires positive buy and free quantities.', 16, 1)
        RETURN
    END

    SET @DealQuantity = @BuyQuantity + @FreeQuantity

    IF @DealQuantity <= 0
    BEGIN
        RAISERROR('BUY N GET N deal quantity is invalid.', 16, 1)
        RETURN
    END

    SELECT @DealAppliesToID = COUNT(1)
    FROM POS_OFFERITEMMAP
    WHERE OFFERID = @DealID
        AND DELETEDDATE IS NULL

    CREATE TABLE #BilledItems
    (
        BILLDETAILID INT NOT NULL PRIMARY KEY,
        ITEMPRICEID INT NOT NULL,
        TOTALQUANTITY INT NOT NULL,
        REMAININGQUANTITY INT NOT NULL,
        MRPQUANTITY INT NOT NULL DEFAULT 0,
        SALEPRICEQUANTITY INT NOT NULL DEFAULT 0,
        FREEQUANTITY INT NOT NULL DEFAULT 0,
        MRP DECIMAL(18, 2) NOT NULL
    )

    IF @DealAppliesToID = 1
    BEGIN
        INSERT INTO #BilledItems(BILLDETAILID, ITEMPRICEID, TOTALQUANTITY, REMAININGQUANTITY, MRP)
        SELECT BD.BILLDETAILID, BD.ITEMPRICEID, BD.QUANTITY, BD.QUANTITY, IP.MRP
        FROM POS_BILLDETAIL BD
            INNER JOIN POS_ITEMPRICE IP ON IP.ITEMPRICEID = BD.ITEMPRICEID
        WHERE BD.BILLDETAILID = @BillDetailID
            AND BD.DELETEDDATE IS NULL
    END
    ELSE
    BEGIN
        INSERT INTO #BilledItems(BILLDETAILID, ITEMPRICEID, TOTALQUANTITY, REMAININGQUANTITY, MRP)
        SELECT BD.BILLDETAILID, BD.ITEMPRICEID, BD.QUANTITY, BD.QUANTITY, IP.MRP
        FROM POS_BILLDETAIL BD
            INNER JOIN POS_ITEMPRICE IP ON IP.ITEMPRICEID = BD.ITEMPRICEID
            INNER JOIN POS_OFFERITEMMAP OFRITM ON OFRITM.ITEMCODEID = IP.ITEMCODEID
        WHERE BD.BILLID = @BillID
            AND BD.DELETEDDATE IS NULL
            AND OFRITM.OFFERID = @DealID
            AND OFRITM.DELETEDDATE IS NULL
    END

    SELECT @TotalEligibleQuantity = SUM(TOTALQUANTITY)
    FROM #BilledItems

    SELECT
        @CompleteDeals = ISNULL(@TotalEligibleQuantity, 0) / @DealQuantity,
        @PaidQuantity = (ISNULL(@TotalEligibleQuantity, 0) / @DealQuantity) * @BuyQuantity,
        @FreeQuantityToAllocate = (ISNULL(@TotalEligibleQuantity, 0) / @DealQuantity) * @FreeQuantity,
        @SalePriceQuantityToAllocate = ISNULL(@TotalEligibleQuantity, 0) % @DealQuantity

    WHILE @FreeQuantityToAllocate > 0
    BEGIN
        DECLARE @FreeBillDetailID INT, @CurrentQuantity INT, @QuantityToUpdate INT

        SELECT TOP 1
            @FreeBillDetailID = BILLDETAILID,
            @CurrentQuantity = REMAININGQUANTITY
        FROM #BilledItems
        WHERE REMAININGQUANTITY > 0
        ORDER BY MRP ASC, BILLDETAILID ASC

        IF ISNULL(@FreeBillDetailID, 0) = 0
            BREAK

        SELECT @QuantityToUpdate =
            CASE WHEN @CurrentQuantity >= @FreeQuantityToAllocate THEN @FreeQuantityToAllocate ELSE @CurrentQuantity END

        UPDATE #BilledItems
        SET
            REMAININGQUANTITY = REMAININGQUANTITY - @QuantityToUpdate,
            FREEQUANTITY = FREEQUANTITY + @QuantityToUpdate
        WHERE BILLDETAILID = @FreeBillDetailID

        SELECT @FreeQuantityToAllocate = @FreeQuantityToAllocate - @QuantityToUpdate
    END

    WHILE @SalePriceQuantityToAllocate > 0
    BEGIN
        DECLARE @SalePriceBillDetailID INT, @SalePriceCurrentQuantity INT, @SalePriceQuantityToUpdate INT

        SELECT TOP 1
            @SalePriceBillDetailID = BILLDETAILID,
            @SalePriceCurrentQuantity = REMAININGQUANTITY
        FROM #BilledItems
        WHERE REMAININGQUANTITY > 0
        ORDER BY MRP ASC, BILLDETAILID ASC

        IF ISNULL(@SalePriceBillDetailID, 0) = 0
            BREAK

        SELECT @SalePriceQuantityToUpdate =
            CASE WHEN @SalePriceCurrentQuantity >= @SalePriceQuantityToAllocate THEN @SalePriceQuantityToAllocate ELSE @SalePriceCurrentQuantity END

        UPDATE #BilledItems
        SET
            REMAININGQUANTITY = REMAININGQUANTITY - @SalePriceQuantityToUpdate,
            SALEPRICEQUANTITY = SALEPRICEQUANTITY + @SalePriceQuantityToUpdate
        WHERE BILLDETAILID = @SalePriceBillDetailID

        SELECT @SalePriceQuantityToAllocate = @SalePriceQuantityToAllocate - @SalePriceQuantityToUpdate
    END

    UPDATE #BilledItems
    SET MRPQUANTITY = REMAININGQUANTITY

    UPDATE BD
    SET
        BD.BILLEDAMOUNT =
            (BI.MRPQUANTITY * IP.MRP)
            + (BI.SALEPRICEQUANTITY * (IP.MRP - ISNULL(dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(IP.ITEMPRICEID, BI.SALEPRICEQUANTITY), IP.ITEMPRICEID), IP.MRP - IP.SALEPRICE))),
        BD.DISCOUNT =
            (BI.FREEQUANTITY * IP.MRP)
            + (BI.SALEPRICEQUANTITY * ISNULL(dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(IP.ITEMPRICEID, BI.SALEPRICEQUANTITY), IP.ITEMPRICEID), IP.MRP - IP.SALEPRICE)),
        BD.OFFERID =
            CASE WHEN @CompleteDeals > 0 THEN @DealID ELSE dbo.UDF_GETOFFER(IP.ITEMPRICEID, BI.TOTALQUANTITY) END
    FROM POS_BILLDETAIL BD
        INNER JOIN #BilledItems BI ON BI.BILLDETAILID = BD.BILLDETAILID
        INNER JOIN POS_ITEMPRICE IP ON IP.ITEMPRICEID = BD.ITEMPRICEID

    SELECT BILLDETAILID, TOTALQUANTITY, MRPQUANTITY, SALEPRICEQUANTITY, FREEQUANTITY
    FROM #BilledItems
END
