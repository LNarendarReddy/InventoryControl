CREATE   PROCEDURE [dbo].[POS_USP_RECALCULATE_OFFER1006]
    @BillID INT,
    @DealID INT,
    @BillDetailID INT = NULL,
    @Quantity INT = NULL,
    @QuantityOrWeightMultiplier DECIMAL(7, 2) = NULL,
    @IsDeleteRecalculation BIT = 0
AS
BEGIN
    SET NOCOUNT ON;


    DECLARE @Offer1006ID INT,
        @Offer1006NoOfItemsToBuy INT,
        @Offer1006NoOfFreeItems INT,
        @Offer1006FreePrice DECIMAL(18, 2),
        @Offer1006TotalBuyQty INT,
        @Offer1006TotalFreeQty INT,
        @Offer1006BuyCycleCount INT,
        @Offer1006FreeCycleCount INT,
        @Offer1006CycleCount INT,
        @Offer1006BuyOfferQty INT,
        @Offer1006FreeOfferQty INT,
        @Offer1006HasFreeItems BIT


    SELECT
        OFR.OFFERID,
        OFR.NUMBEROFITEMS,
        ISNULL(OFR.NUMBEROFFREEITEMS, 1) AS NUMBEROFFREEITEMS,
        ISNULL(OFR.OFFERTHRESHOLDPRICE, 0.00) AS FREEITEMPRICE
    INTO #Offer1006Candidates
    FROM POS_OFFER OFR
        INNER JOIN POS_OFFERBRANCH OFRB ON OFRB.OFFERID = OFR.OFFERID
    WHERE OFR.OFFERID = @DealID
        AND OFRB.DELETEDDATE IS NULL


    SELECT
        OFRMAP.OFFERITEMMAPID,
        OFRMAP.OFFERID,
        OFRMAP.ITEMCODEID,
        CASE WHEN LOWER(ISNULL(JSON_VALUE(OFRMAP.OFFERITEMCONFIG, '$.IsFreeItem'), '0')) IN ('1', 'true') THEN 1 ELSE 0 END AS IsFreeItem,
        TRY_CONVERT(INT, JSON_VALUE(OFRMAP.OFFERITEMCONFIG, '$.ItemPriceID')) AS ItemPriceID,
        UPPER(ISNULL(JSON_VALUE(OFRMAP.OFFERITEMCONFIG, '$.PriceBasedOn'), 'MRP')) AS PriceBasedOn,
        TRY_CONVERT(DECIMAL(18, 2), JSON_VALUE(OFRMAP.OFFERITEMCONFIG, '$.OfferPrice')) AS OfferPrice
    INTO #Offer1006Config
    FROM POS_OFFERITEMMAP OFRMAP
        INNER JOIN #Offer1006Candidates OFR ON OFR.OFFERID = OFRMAP.OFFERID
    WHERE OFRMAP.DELETEDDATE IS NULL


    DELETE FROM #Offer1006Config
    WHERE ITEMCODEID IS NULL OR ItemPriceID IS NULL


    SELECT TOP 1
        @Offer1006ID = C.OFFERID,
        @Offer1006NoOfItemsToBuy = C.NUMBEROFITEMS,
        @Offer1006NoOfFreeItems = C.NUMBEROFFREEITEMS,
        @Offer1006FreePrice = C.FREEITEMPRICE,
        @Offer1006TotalBuyQty = SUM(PBD.QUANTITY),
        @Offer1006HasFreeItems =
            CASE WHEN EXISTS (SELECT 1 FROM #Offer1006Config OC WHERE OC.OFFERID = C.OFFERID AND OC.IsFreeItem = 1)
            THEN 1 ELSE 0 END
    FROM #Offer1006Candidates C
        INNER JOIN #Offer1006Config OC ON OC.OFFERID = C.OFFERID AND OC.IsFreeItem = 0
        INNER JOIN POS_ITEMPRICE IP ON IP.ITEMCODEID = OC.ITEMCODEID
        INNER JOIN POS_BILLDETAIL PBD ON PBD.ITEMPRICEID = IP.ITEMPRICEID
    WHERE PBD.BILLID = @BillID
        AND PBD.DELETEDDATE IS NULL
    GROUP BY C.OFFERID, C.NUMBEROFITEMS, C.NUMBEROFFREEITEMS, C.FREEITEMPRICE
    ORDER BY C.NUMBEROFITEMS DESC, C.OFFERID DESC


    IF ISNULL(@Offer1006ID, 0) > 0 AND ISNULL(@Offer1006NoOfItemsToBuy, 0) > 0
    BEGIN
        SELECT @Offer1006BuyCycleCount = ISNULL(@Offer1006TotalBuyQty, 0) / @Offer1006NoOfItemsToBuy


        IF @Offer1006HasFreeItems = 1
        BEGIN
            SELECT @Offer1006TotalFreeQty = SUM(PBD.QUANTITY)
            FROM #Offer1006Config OC
                INNER JOIN POS_BILLDETAIL PBD ON PBD.ITEMPRICEID = OC.ItemPriceID
            WHERE OC.OFFERID = @Offer1006ID
                AND OC.IsFreeItem = 1
                AND PBD.BILLID = @BillID
                AND PBD.DELETEDDATE IS NULL


            SELECT @Offer1006FreeCycleCount = ISNULL(@Offer1006TotalFreeQty, 0) / ISNULL(NULLIF(@Offer1006NoOfFreeItems, 0), 1)


            SELECT @Offer1006CycleCount =
                CASE WHEN @Offer1006BuyCycleCount <= @Offer1006FreeCycleCount
                    THEN @Offer1006BuyCycleCount ELSE @Offer1006FreeCycleCount END
        END
        ELSE
        BEGIN
            SELECT @Offer1006CycleCount = @Offer1006BuyCycleCount
        END


        SELECT @Offer1006BuyOfferQty =
            CASE
                WHEN @Offer1006HasFreeItems = 0 AND @Offer1006CycleCount > 0 THEN @Offer1006TotalBuyQty
                ELSE @Offer1006CycleCount * @Offer1006NoOfItemsToBuy
            END


        SELECT @Offer1006FreeOfferQty =
            CASE WHEN @Offer1006HasFreeItems = 1 THEN @Offer1006CycleCount * @Offer1006NoOfFreeItems ELSE 0 END


        SELECT
            PBD.BILLDETAILID,
            PBD.ITEMPRICEID,
            OC.OFFERITEMMAPID,
            1 AS ISBUYITEM,
            PBD.QUANTITY AS TOTALQTY,
            0 AS OFFERQTY,
            0 AS FREEQTY,
            0 AS NORMALQTY,
            OC.PriceBasedOn,
            OC.OfferPrice,
            IP.MRP,
            IP.SALEPRICE
        INTO #Offer1006Lines
        FROM #Offer1006Config OC
            INNER JOIN POS_ITEMPRICE IP ON IP.ITEMCODEID = OC.ITEMCODEID
            INNER JOIN POS_BILLDETAIL PBD ON PBD.ITEMPRICEID = IP.ITEMPRICEID
        WHERE OC.OFFERID = @Offer1006ID
            AND OC.IsFreeItem = 0
            AND PBD.BILLID = @BillID
            AND PBD.DELETEDDATE IS NULL


        INSERT INTO #Offer1006Lines
        SELECT
            PBD.BILLDETAILID,
            PBD.ITEMPRICEID,
            OC.OFFERITEMMAPID,
            0 AS ISBUYITEM,
            PBD.QUANTITY AS TOTALQTY,
            0 AS OFFERQTY,
            0 AS FREEQTY,
            0 AS NORMALQTY,
            OC.PriceBasedOn,
            OC.OfferPrice,
            IP.MRP,
            IP.SALEPRICE
        FROM #Offer1006Config OC
            INNER JOIN POS_BILLDETAIL PBD ON PBD.ITEMPRICEID = OC.ItemPriceID
            INNER JOIN POS_ITEMPRICE IP ON IP.ITEMPRICEID = PBD.ITEMPRICEID
        WHERE OC.OFFERID = @Offer1006ID
            AND OC.IsFreeItem = 1
            AND PBD.BILLID = @BillID
            AND PBD.DELETEDDATE IS NULL
            AND NOT EXISTS
            (
                SELECT 1
                FROM #Offer1006Lines L
                WHERE L.BILLDETAILID = PBD.BILLDETAILID
            )


        DECLARE @Offer1006RemainingBuyQty INT = @Offer1006BuyOfferQty,
            @Offer1006RemainingFreeQty INT = @Offer1006FreeOfferQty,
            @Offer1006CurBillDetailID INT,
            @Offer1006CurQty INT,
            @Offer1006QtyToApply INT


        WHILE @Offer1006RemainingBuyQty > 0
        BEGIN
            SELECT TOP 1
                @Offer1006CurBillDetailID = BILLDETAILID,
                @Offer1006CurQty = TOTALQTY - OFFERQTY - FREEQTY - NORMALQTY
            FROM #Offer1006Lines
            WHERE ISBUYITEM = 1
                AND TOTALQTY - OFFERQTY - FREEQTY - NORMALQTY > 0
            ORDER BY MRP DESC, OFFERITEMMAPID ASC


            IF ISNULL(@Offer1006CurBillDetailID, 0) = 0
                BREAK


            SELECT @Offer1006QtyToApply =
                CASE WHEN @Offer1006CurQty >= @Offer1006RemainingBuyQty THEN @Offer1006RemainingBuyQty ELSE @Offer1006CurQty END


            UPDATE #Offer1006Lines
            SET OFFERQTY = OFFERQTY + @Offer1006QtyToApply
            WHERE BILLDETAILID = @Offer1006CurBillDetailID


            SELECT @Offer1006RemainingBuyQty = @Offer1006RemainingBuyQty - @Offer1006QtyToApply
            SELECT @Offer1006CurBillDetailID = NULL, @Offer1006CurQty = NULL, @Offer1006QtyToApply = NULL
        END


        WHILE @Offer1006RemainingFreeQty > 0
        BEGIN
            SELECT TOP 1
                @Offer1006CurBillDetailID = BILLDETAILID,
                @Offer1006CurQty = TOTALQTY - OFFERQTY - FREEQTY - NORMALQTY
            FROM #Offer1006Lines
            WHERE ISBUYITEM = 0
                AND TOTALQTY - OFFERQTY - FREEQTY - NORMALQTY > 0
            ORDER BY MRP ASC, OFFERITEMMAPID ASC


            IF ISNULL(@Offer1006CurBillDetailID, 0) = 0
                BREAK


            SELECT @Offer1006QtyToApply =
                CASE WHEN @Offer1006CurQty >= @Offer1006RemainingFreeQty THEN @Offer1006RemainingFreeQty ELSE @Offer1006CurQty END


            UPDATE #Offer1006Lines
            SET FREEQTY = FREEQTY + @Offer1006QtyToApply
            WHERE BILLDETAILID = @Offer1006CurBillDetailID


            SELECT @Offer1006RemainingFreeQty = @Offer1006RemainingFreeQty - @Offer1006QtyToApply
            SELECT @Offer1006CurBillDetailID = NULL, @Offer1006CurQty = NULL, @Offer1006QtyToApply = NULL
        END


        UPDATE #Offer1006Lines
        SET NORMALQTY = TOTALQTY - OFFERQTY - FREEQTY


        UPDATE PBD
        SET
            PBD.BILLEDAMOUNT =
                ((L.OFFERQTY + L.FREEQTY)
                    * CASE L.PriceBasedOn WHEN 'SP' THEN L.SALEPRICE WHEN 'OP' THEN ISNULL(L.OfferPrice, L.MRP) ELSE L.MRP END)
                + (L.NORMALQTY * (L.MRP - ISNULL(dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(L.ITEMPRICEID, L.NORMALQTY), L.ITEMPRICEID), L.MRP - L.SALEPRICE))),


            PBD.DISCOUNT =
                ((L.OFFERQTY + L.FREEQTY)
                    * (L.MRP - CASE L.PriceBasedOn WHEN 'SP' THEN L.SALEPRICE WHEN 'OP' THEN ISNULL(L.OfferPrice, L.MRP) ELSE L.MRP END))
                + (L.NORMALQTY * ISNULL(dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(L.ITEMPRICEID, L.NORMALQTY), L.ITEMPRICEID), L.MRP - L.SALEPRICE)),


            PBD.OFFERID =
                CASE WHEN L.OFFERQTY > 0 OR L.FREEQTY > 0 THEN @Offer1006ID ELSE dbo.UDF_GETOFFER(L.ITEMPRICEID, L.NORMALQTY) END
        FROM POS_BILLDETAIL PBD
            INNER JOIN #Offer1006Lines L ON L.BILLDETAILID = PBD.BILLDETAILID


        SELECT L.BILLDETAILID, L.TOTALQTY, L.OFFERQTY, L.NORMALQTY, L.FREEQTY
        FROM #Offer1006Lines L
    END
    ELSE IF @IsDeleteRecalculation = 1
    BEGIN
        SELECT
            PBD.BILLDETAILID,
            PBD.ITEMPRICEID,
            PBD.QUANTITY,
            IP.MRP,
            IP.SALEPRICE
        INTO #Offer1006ResetLines
        FROM POS_BILLDETAIL PBD
            INNER JOIN POS_ITEMPRICE IP ON IP.ITEMPRICEID = PBD.ITEMPRICEID
        WHERE PBD.BILLID = @BillID
            AND PBD.OFFERID = @DealID
            AND PBD.DELETEDDATE IS NULL


        UPDATE PBD
        SET
            PBD.BILLEDAMOUNT = L.QUANTITY * (L.MRP - ISNULL(dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(L.ITEMPRICEID, L.QUANTITY), L.ITEMPRICEID), L.MRP - L.SALEPRICE)),
            PBD.DISCOUNT = L.QUANTITY * ISNULL(dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(L.ITEMPRICEID, L.QUANTITY), L.ITEMPRICEID), L.MRP - L.SALEPRICE),
            PBD.OFFERID = dbo.UDF_GETOFFER(L.ITEMPRICEID, L.QUANTITY)
        FROM POS_BILLDETAIL PBD
            INNER JOIN #Offer1006ResetLines L ON L.BILLDETAILID = PBD.BILLDETAILID


        SELECT L.BILLDETAILID, L.QUANTITY AS TOTALQTY, 0 AS OFFERQTY, L.QUANTITY AS NORMALQTY, 0 AS FREEQTY
        FROM #Offer1006ResetLines L
    END
    ELSE
    BEGIN
        UPDATE BD
        SET
            BD.BILLEDAMOUNT =
                ISNULL(@QuantityOrWeightMultiplier, @Quantity)
                * (IP.MRP - ISNULL(dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(IP.ITEMPRICEID, @Quantity), IP.ITEMPRICEID), IP.MRP - IP.SALEPRICE)),


            BD.DISCOUNT =
                ISNULL(@QuantityOrWeightMultiplier, @Quantity)
                * ISNULL(dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(IP.ITEMPRICEID, @Quantity), IP.ITEMPRICEID), IP.MRP - IP.SALEPRICE),


            BD.OFFERID = dbo.UDF_GETOFFER(IP.ITEMPRICEID, @Quantity)
        FROM POS_BILLDETAIL BD
            INNER JOIN POS_ITEMPRICE IP ON IP.ITEMPRICEID = BD.ITEMPRICEID
        WHERE BD.BILLDETAILID = @BillDetailID


        SELECT @BillDetailID AS BILLDETAILID, @Quantity AS TOTALQTY, 0 AS OFFERQTY, 0 AS NORMALQTY, 0 AS FREEQTY
    END
