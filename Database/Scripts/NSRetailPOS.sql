			WHEN ISNULL(@FreeItemPurchasedQuantity, 0) > ISNULL(@FreeItemNoOfFreeItems, 1) THEN ISNULL(@FreeItemNoOfFreeItems, 1)
			ELSE ISNULL(@FreeItemPurchasedQuantity, 0)
		END

