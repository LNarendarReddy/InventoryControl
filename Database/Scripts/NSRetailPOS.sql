	@SpecialDiscountPer DECIMAL(4, 2)
	, @UserID INT
AS
BEGIN
	
	UPDATE POS_BILL SET SPLDISCPER = @SpecialDiscountPer WHERE BILLID = @BillID

	UPDATE BD 
	SET 
		BD.BILLEDAMOUNT = (CASE WHEN ISNULL(I.ISOPENITEM, 1) = 1 THEN BD.WEIGHTINKGS ELSE BD.QUANTITY END) * 
							(IP.SALEPRICE - (IP.SALEPRICE * @SpecialDiscountPer / 100))
		, BD.DISCOUNT = (CASE WHEN ISNULL(I.ISOPENITEM, 1) = 1 THEN BD.WEIGHTINKGS ELSE BD.QUANTITY END) * 
