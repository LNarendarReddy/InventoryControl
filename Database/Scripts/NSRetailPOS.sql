CREATE   PROCEDURE [dbo].[POS_USP_D_BILLDETAIL_V1]
    @BillDetailID INT,
    @UserID INT,
    @SNos POS_BILLDETAILSNO READONLY
AS
BEGIN

    UPDATE POS_BILLDETAIL
    SET DELETEDDATE = GETDATE()
    WHERE BILLDETAILID = @BillDetailID;

    UPDATE BD
    SET SNO = SNOS.SNO
    FROM POS_BILLDETAIL BD
    INNER JOIN @SNos SNOS
        ON SNOS.BILLDETAILID = BD.BILLDETAILID;

    DECLARE
        @OfferID INT,
        @DealID INT,
        @OfferAppliesToID INT,
        @DealAppliesToID INT,
        @ItemPriceID INT,
        @BillID INT,
        @BuyDealID INT = 0,
        @BuyDealTypeID INT,
        @DeletedQuantity INT;

    SELECT
        @ItemPriceID = ITEMPRICEID,
        @BillID = BILLID,
        @BuyDealID = OFFERID,
        @DeletedQuantity = QUANTITY
    FROM POS_BILLDETAIL
    WHERE BILLDETAILID = @BillDetailID;

    SELECT
        @OfferID = OFFERID,
        @OfferAppliesToID = OFFERAPPLIESTOID,
        @DealID = DEALID,
        @DealAppliesToID = DEALAPPLIESTOID
    FROM UDF_GETOFFERS_V1(@ItemPriceID, 0);

    SELECT
        @BuyDealTypeID = OFFERTYPEID
    FROM POS_OFFER
    WHERE OFFERID = @BuyDealID
        AND ISNULL(@BuyDealID, 0) > 0;

    CREATE TABLE #BilledGroupItems
    (
        BILLDETAILID INT,
        TOTALQUANTITY INT,
        MRPQUANTITY INT,
        SALEPRICEQUANTITY INT,
        FREEQUANTITY INT
    );

    IF @BuyDealTypeID = 1006
        AND
        (
            SELECT COUNT(1)
            FROM POS_OFFERITEMMAP
            WHERE OFFERID = @BuyDealID
                AND DELETEDDATE IS NULL
        ) > 1
    BEGIN

        INSERT INTO #BilledGroupItems
        EXEC dbo.POS_USP_RECALCULATE_OFFER1006
            @BillID,
            @BuyDealID,
            @BillDetailID,
            @DeletedQuantity,
            @DeletedQuantity,
            1;

    END
    ELSE IF @BuyDealTypeID = 1010
        AND
        (
            SELECT COUNT(1)
            FROM POS_OFFERITEMMAP
            WHERE OFFERID = @BuyDealID
                AND DELETEDDATE IS NULL
        ) > 1
    BEGIN

        INSERT INTO #BilledGroupItems
        EXEC dbo.POS_USP_RECALCULATE_OFFER1010
            @BillID,
            @BuyDealID,
            @BillDetailID,
            @DeletedQuantity,
            @DeletedQuantity;

    END;

    UPDATE BD
    SET
        BD.CGST = ROUND((BD.BILLEDAMOUNT * GST.CGST) / 100, 2),
        BD.SGST = ROUND((BD.BILLEDAMOUNT * GST.SGST) / 100, 2),
        BD.CESS = ROUND((BD.BILLEDAMOUNT * GST.CESS) / 100, 2),
        BD.GSTVALUE =
            ROUND(
                (
                    BD.BILLEDAMOUNT
                    * (
                        GST.CGST
                        + GST.SGST
                        + GST.IGST
                        + GST.CESS
                    )
                ) / 100,
                2
            )
    FROM POS_BILLDETAIL BD
    INNER JOIN #BilledGroupItems BGI
        ON BGI.BILLDETAILID = BD.BILLDETAILID
    INNER JOIN POS_GSTDETAIL GST
        ON GST.GSTID = BD.GSTID;

    SELECT
        BD.BILLDETAILID,
        B.BILLID,
        IP.ITEMPRICEID,
        BD.SNO,
        I.ITEMNAME,
        IC.ITEMCODE,
        ISNULL(IC.HSNCODE, '') AS HSNCODE,
        IP.MRP,
        IP.SALEPRICE,
        GST.GSTCODE,
        BD.QUANTITY,
        BD.WEIGHTINKGS,
        BD.BILLEDAMOUNT,
        BD.CGST,
        BD.SGST,
        BD.IGST,
        BD.CESS,
        BD.GSTVALUE,
        BD.GSTID,
        GST.CGST AS CGSTDESC,
        GST.SGST AS SGSTDESC,
        GST.CESS AS CESSDESC,
        ISNULL(I.ISOPENITEM, 0) AS ISOPENITEM,
        DISCOUNT,
        BD.OFFERID,
        CASE
            WHEN OFRTYP.OFFERTYPEID = 1010 THEN
                OFRTYP.OFFERTYPECODE
                + '('
                + CAST(ISNULL(OFR.NUMBEROFITEMS, 0) AS VARCHAR(10))
                + ', '
                + CAST(ISNULL(OFR.NUMBEROFFREEITEMS, 0) AS VARCHAR(10))
                + ')'
            ELSE OFRTYP.OFFERTYPECODE
        END AS OFFERTYPECODE
    FROM POS_BILLDETAIL BD
    INNER JOIN #BilledGroupItems BGI
        ON BGI.BILLDETAILID = BD.BILLDETAILID
    INNER JOIN POS_BILL B
        ON B.BILLID = BD.BILLID
    INNER JOIN POS_ITEMPRICE IP
        ON IP.ITEMPRICEID = BD.ITEMPRICEID
    INNER JOIN POS_ITEMCODE IC
        ON IC.ITEMCODEID = IP.ITEMCODEID
    INNER JOIN POS_ITEM I
        ON I.ITEMID = IC.ITEMID
    INNER JOIN POS_GSTDETAIL GST
        ON GST.GSTID = IP.GSTID
    LEFT JOIN POS_OFFER OFR
        ON OFR.OFFERID = BD.OFFERID
    LEFT JOIN POS_OFFERTYPE OFRTYP
        ON OFRTYP.OFFERTYPEID = OFR.OFFERTYPEID;

END;
