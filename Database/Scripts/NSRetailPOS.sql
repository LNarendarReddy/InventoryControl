	DELETE PBD FROM POS_BILLDETAIL PBD WHERE dbo.UDF_GET_LAST_MODIFIED_DATE(CREATEDDATE, UPDATEDDATE, DELETEDDATE) < @CutOffDate
		AND NOT EXISTS (SELECT 1 FROM POS_CREFUND PCR WHERE PCR.BILLDETAILID = PBD.BILLDETAILID)
