				BO.MRPQTY *
				(IP.MRP -
					CASE BO.PriceBasedOn
						WHEN 'SP' THEN IP.SALEPRICE
						WHEN 'OP' THEN ISNULL(BO.OfferPrice, IP.MRP)
						ELSE IP.MRP
					END
				)
				+ (BO.FREEQTY * (IP.MRP - @FreeItemPrice))
				+ (BO.SALEPRICEQTY * dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(IP.ITEMPRICEID, BO.SALEPRICEQTY), IP.ITEMPRICEID)),

			PBD.OFFERID = BO.OFFERID
		FROM
