				BO.MRPQTY *
				CASE BO.PriceBasedOn
					WHEN 'SP' THEN IP.SALEPRICE
					WHEN 'OP' THEN ISNULL(BO.OfferPrice, IP.MRP)
					ELSE IP.MRP
