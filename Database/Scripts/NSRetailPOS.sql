CREATE   PROCEDURE [dbo].[POS_USP_CU_BREFUND]
@USERID INT,                
@BRANCHID INT,
@CATEGORYID INT
AS                  
BEGIN                  
                  
	DECLARE @BREFUNDID INT = 0,@BREFUNDNUMBER NVARCHAR(50)
	SELECT @BREFUNDID = ISNULL(BREFUNDID,0),                
	@BREFUNDNUMBER = BREFUNDNUMBER FROM POS_BREFUND                   
	WHERE CREATEDBY = @USERID AND STATUS = 0 AND DELETEDDATE IS NULL AND CATEGORYID IS NULL
                
	IF(@BREFUNDID = 0)                
	BEGIN                
                
		INSERT INTO POS_BREFUND(BRANCHID,BREFUNDNUMBER,CREATEDBY,CREATEDATE,STATUS,CATEGORYID)                
		SELECT @BRANCHID,@BREFUNDNUMBER,@USERID,GETDATE(),0, @CATEGORYID
                
		SET @BREFUNDID = SCOPE_IDENTITY()  
                
		SELECT @BREFUNDNUMBER =                 
		'BR-' + Bc.COUNTERNAME + '/' +                 
		REPLACE(CAST(CONVERT(date,GETDATE(),10) AS VARCHAR(15)),'-','') + '/' +          
		RIGHT('0000' + CAST(@BREFUNDID AS varchar(10)) , 5)          
          
		FROM POS_POSDETAILS POS                
		INNER JOIN POS_BRANCHCOUNTER Bc ON POS.BRANCHCOUNTERID = BC.COUNTERID        
                
		UPDATE POS_BREFUND SET BREFUNDNUMBER = @BREFUNDNUMBER                
		WHERE BREFUNDID = @BREFUNDID                
                
	END                
                
	SELECT @BREFUNDID AS BREFUNDID, @BREFUNDNUMBER AS BREFUNDNUMBER, @CATEGORYID AS CATEGORYID
                  
END 
