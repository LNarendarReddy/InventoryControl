CREATE   PROCEDURE [dbo].[USP_R_ITEMDATAFORITEMDETAILS] 
@ITEMCODEID INT
AS
BEGIN
	
	SELECT * 
	INTO #ITEMPRICES
	FROM
		(
	
			SELECT 
				PIP.ITEMPRICEID, PIP.MRP, PIP.SALEPRICE, OT.OFFERTYPENAME, OFR.OFFERCODE, OFR.OFFERVALUE
				, CASE 
					WHEN OT.OFFERTYPECODE = 'DF' THEN PIP.MRP - OFR.OFFERVALUE
					WHEN OT.OFFERTYPECODE = 'DP' THEN PIP.MRP - CAST(( PIP.MRP * OFR.OFFERVALUE / 100) AS DECIMAL(12, 2))
					WHEN OT.OFFERTYPECODE = 'FR' THEN OFR.OFFERVALUE
				END AS FINALPRICE
			FROM 
				POS_ITEMPRICE PIP
				CROSS APPLY UDF_GETOFFERS(PIP.ITEMPRICEID , 1) OFRS
				INNER JOIN POS_OFFER OFR ON OFRS.OFFERID = OFR.OFFERID AND OFR.DELETEDDATE IS NULL
				INNER JOIN POS_OFFERTYPE OT ON OFR.OFFERTYPEID = OT.OFFERTYPEID
				INNER JOIN POS_OFFERBRANCH OB ON OB.OFFERID = OFR.OFFERID AND OB.DELETEDDATE IS NULL
			WHERE PIP.ITEMCODEID = @ITEMCODEID
				AND PIP.DELETEDDATE IS NULL
				AND QTYORWEIGHTINKGS > 0

			UNION ALL

			SELECT 
				PIP.ITEMPRICEID, PIP.MRP, PIP.SALEPRICE, OT.OFFERTYPENAME, OFR.OFFERCODE, NULL AS OFFERVALUE, NULL AS FINALPRICE
			FROM 
				POS_ITEMPRICE PIP
				CROSS APPLY UDF_GETOFFERS(PIP.ITEMPRICEID , 1) OFRS		
				INNER JOIN POS_OFFER OFR ON OFRS.DEALID = OFR.OFFERID AND OFR.DELETEDDATE IS NULL
				INNER JOIN POS_OFFERTYPE OT ON OFR.OFFERTYPEID = OT.OFFERTYPEID
				INNER JOIN POS_OFFERBRANCH OB ON OB.OFFERID = OFR.OFFERID AND OB.DELETEDDATE IS NULL
			WHERE PIP.ITEMCODEID = @ITEMCODEID
				AND PIP.DELETEDDATE IS NULL
				AND QTYORWEIGHTINKGS > 0
		) ITEMPRICES
		
	INSERT INTO #ITEMPRICES
	SELECT PIP.ITEMPRICEID, PIP.MRP, PIP.SALEPRICE, NULL, NULL, NULL, NULL
	FROM 
		POS_ITEMPRICE PIP
	WHERE PIP.ITEMCODEID = @ITEMCODEID
		AND PIP.DELETEDDATE IS NULL
		AND QTYORWEIGHTINKGS > 0
		AND NOT EXISTS 
			(
				SELECT 1 FROM #ITEMPRICES IP WHERE IP.ITEMPRICEID = PIP.ITEMPRICEID
			)

	SELECT * FROM #ITEMPRICES ORDER BY MRP, SALEPRICE, ISNULL(FINALPRICE, 1000 * 1000)


	--SELECT MRP, SALEPRICE
