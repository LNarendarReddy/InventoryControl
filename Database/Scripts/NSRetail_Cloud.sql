CREATE PROCEDURE [dbo].[USP_U_POS_RELEASEBUILD]
(
    @CounterIDs dbo.BRANCHCOUNTERIDTYPE READONLY,
    @USERID INT
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @AppVersion NVARCHAR(50);
    DECLARE @DBVersion NVARCHAR(50);

    SELECT @AppVersion = LTRIM(RTRIM(CONFIGVALUE))
    FROM dbo.TBLCONFIG
    WHERE CONFIGNAME = 'AppVersion';

    SELECT @DBVersion = LTRIM(RTRIM(CONFIGVALUE))
    FROM dbo.TBLCONFIG
    WHERE CONFIGNAME = 'DBVersion';

    IF ISNULL(@AppVersion, '') = '' OR ISNULL(@DBVersion, '') = ''

    BEGIN
        RAISERROR('Latest App Version or DB Version is not configured.', 16, 1);
        RETURN;
    END

    IF NOT EXISTS
    (
        SELECT 1
        FROM dbo.BRANCHCOUNTER BC
        INNER JOIN @CounterIDs CI ON CI.COUNTERID = BC.COUNTERID
        WHERE BC.DELETEDDATE IS NULL
          AND
          (
              ISNULL(BC.TARGETAPPVERSION, '') <> @AppVersion
              OR ISNULL(BC.TARGETDBVERSION, '') <> @DBVersion
          )
    )
    BEGIN
        RAISERROR('Selected counters ar
e already released to the latest version.', 16, 1);
        RETURN;
    END

    UPDATE BC
    SET
        TARGETAPPVERSION = @AppVersion,
        TARGETDBVERSION = @DBVersion,
        BUILDRELEASEDATE = GETDATE(),
        BUILDRELEASEBY = @USERID
    FROM dbo.BRANCHCOUNTER BC
    INNER JOIN @CounterIDs CI ON CI.COUNTERID = BC.COUNTERID
    WHERE BC.DELETEDDATE IS NULL
      AND
      (
          ISNULL(BC.TARGETAPPVERSION, '') <> @AppVersion
          OR ISNULL(BC.TARGETDBVERSION, '') <> @DBVersion
     
 );

    SELECT @@ROWCOUNT;
END
