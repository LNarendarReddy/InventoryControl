CREATE   PROCEDURE [dbo].[USP_U_BRANCHCOUNTER_RELEASEBUILD]
(
    @CounterIDs dbo.BRANCHCOUNTERIDTYPE READONLY,
    @USERID INT
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @AppVersion VARCHAR(20);
    DECLARE @DBVersion VARCHAR(20);

    SELECT
        @AppVersion = MAX(CASE WHEN UPPER(CONFIGNAME) = 'APPVERSION' THEN LTRIM(RTRIM(CONFIGVALUE)) END),
        @DBVersion = MAX(CASE WHEN UPPER(CONFIGNAME) = 'DBVERSION' THEN LTRIM(RTRIM(CONFIGVALUE)) END)
    FROM dbo.TBLCONFIG
    WHERE UPPER(CONFIGNAME) IN ('APPVERSION', 'DBVERSION');

    IF ISNULL(@AppVersion, '') = '' OR ISNULL(@DBVersion, '') = ''
    BEGIN
        RAISERROR('Released App Version or DB Version is not configured.', 16, 1);
        RETURN;
    END

    UPDATE BC
    SET
        TARGETAPPVERSION = @AppVersion,
        TARGETDBVERSION = @DBVersion,
        UPDATEDBY = @USERID,
        UPDATEDDATE = GETDATE()
    FROM dbo.BRANCHCOUNTER BC
    INNER JOIN @CounterIDs CI ON CI.COUNTERID = BC.COUNTERID
    WHERE BC.DELETEDDATE IS NULL;

    SELECT @@ROWCOUNT;
END
GO
