		DC.DAYCLOSUREID, DC.CLOSUREDATE, DC.OPENINGBALANCE, DC.CLOSINGBALANCE, DC.CLOSINGDIFFERENCE, DC.CLOSEDBY, DC.REFUNDAMOUNT, DC.CREATEDDATE
		, @COMPLETEDBILLS AS COMPLETEDBILLS, @DRAFTBILLS AS DRAFTBILLS, @VOIDITEMS AS VOIDITEMS,
		B.ADDRESS as Address, B.PHONENO AS PhoneNo, B.BRANCHNAME BranchName, BC.COUNTERNAME AS CounterName, CU.FULLNAME AS UserName
	FROM POS_DAYCLOSURE DC
		INNER JOIN BRANCHCOUNTER BC ON DC.BRANCHCOUNTERID = BC.COUNTERID
		INNER JOIN BRANCH B ON BC.BRANCHID = B.BRANCHID
		INNER JOIN TBLUSER CU ON DC.CLOSEDBY = CU.USERID
	WHERE BRANCHCOUNTERID = @BRANCHCOUNTERID AND DC.DAYCLOSUREID = @DAYCLOSUREID
        
	SELECT 
		DCD.DAYCLOSUREID, DEN.DENOMINATIONID, DEN.DISPLAYVALUE, DCD.CLOSUREVALUE, DEN.MULTIPLIER  
	FROM 
		POS_DAYCLOSUREDETAIL DCD       
		INNER JOIN POS_DENOMINATION DEN ON DCD.DENOMINATIONID = DEN.DENOMINATIONID      
	WHERE COUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID = @DAYCLOSUREID      
	ORDER BY DEN.DENOMINATIONID      

	SELECT 
		BMOP.DAYCLOSUREID, MOP.MOPID,MOP.MOPNAME,
		CASE WHEN MOP.MOPID = 1 THEN ISNULL(BMOP.MOPVALUE,0) - @REFUNDAMOUNT ELSE ISNULL(BMOP.MOPVALUE,0) END AS MOPVALUE
	FROM 
		TBLMOP MOP
		INNER JOIN 
			(
				SELECT BM.DAYCLOSUREID, MOPID, SUM(MOPVALUE) AS MOPVALUE 
				FROM 
					POS_BILLMOPDETAIL BM
					INNER JOIN POS_BILL B ON BM.COUNTERID = B.BRANCHCOUNTERID AND BM.BILLID = B.BILLID
				WHERE BM.COUNTERID = @BRANCHCOUNTERID 
					AND B.DAYCLOSUREID = @DAYCLOSUREID 
					and MOPVALUE > 0
				GROUP BY BM.DAYCLOSUREID,MOPID
			) AS BMOP ON MOP.MOPID = BMOP.MOPID                    
	ORDER BY MOP.MOPID                            

	SELECT PB.DAYCLOSUREID, CU.USERNAME, MOP.MOPNAME, SUM(PBMD.MOPVALUE) MOPVALUE
	FROM POS_BILL PB
		INNER JOIN POS_BILLMOPDETAIL PBMD ON PBMD.COUNTERID = PB.BRANCHCOUNTERID AND PBMD.BILLID = PB.BILLID
		INNER JOIN TBLMOP MOP ON MOP.MOPID = PBMD.MOPID
		INNER JOIN TBLUSER CU ON CU.USERID = PB.CREATEDBY
	WHERE
		PB.BRANCHCOUNTERID = @BRANCHCOUNTERID
		AND PBMD.COUNTERID = @BRANCHCOUNTERID
		AND PB.DAYCLOSUREID = @DAYCLOSUREID 
		AND PBMD.DAYCLOSUREID = @DAYCLOSUREID
		AND PB.BILLSTATUS = 1
     GROUP BY PB.DAYCLOSUREID, CU.USERNAME, MOP.MOPNAME
     ORDER BY CU.USERNAME, MOP.MOPNAME

END
