CREATE PROCEDURE [dbo].[CLOUD_USP_CU_STOCKCOUNTINGDETAIL]            
@STOCKCOUNTINGDETAILID INT,            
@STOCKCOUNTINGID INT,            
@ITEMPRICEID INT,            
@QUANTITY INT ,      
@WEIGHTINKGS DECIMAL(18,2) = 0,
@CREATEDDATE DATETIME      
AS            
BEGIN            
        
	IF NOT EXISTS (SELECT 1 FROM CLOUD_STOCKCOUNTING WHERE STOCKCOUNTINGID = @STOCKCOUNTINGID AND ISNULL(STATUS,0) = 0)
	BEGIN
		SELECT 'Counting sheet already submitted or discarded in other device'
		return;
	END

	IF NOT EXISTS(
		SELECT 1 FROM CLOUD_STOCKCOUNTING SC 
			INNER JOIN  BRANCH B ON SC.BRANCHID = B.BRANCHID 
		WHERE SC.STOCKCOUNTINGID = @STOCKCOUNTINGID 
		AND ISNULL(ENABLESTOCKCOUNTING,0) = 1)
	BEGIN
		SELECT 'Stock counting not enabled for selected branch, Discard current sheet and contact your administrator.'
		return;
	END

	IF(@STOCKCOUNTINGDETAILID > 0)            
	BEGIN            
		UPDATE CLOUD_STOCKCOUNTINGDETAIL            
		SET QUANTITY = @QUANTITY,            
		WEIGHTINKGS = @WEIGHTINKGS,
		UPDATEDDATE = GETUTCDATE() + '05:30'      
		WHERE STOCKCOUNTINGDETAILID = @STOCKCOUNTINGDETAILID            
	END        
        
	ELSE            
        
	BEGIN            
        
		SELECT @STOCKCOUNTINGDETAILID = STOCKCOUNTINGDETAILID FROM CLOUD_STOCKCOUNTINGDETAIL         
		WHERE STOCKCOUNTINGID = @STOCKCOUNTINGID AND ITEMPRICEID = @ITEMPRICEID        
		AND DELETEDDATE IS NULL  
        
		IF(@STOCKCOUNTINGDETAILID > 0)        
		BEGIN        
        
			update CLOUD_STOCKCOUNTINGDETAIL set QUANTITY = QUANTITY + @QUANTITY,      
			WEIGHTINKGS = WEIGHTINKGS + @WEIGHTINKGS,
			UPDATEDDATE = GETUTCDATE() + '05:30'    
			where STOCKCOUNTINGDETAILID = @STOCKCOUNTINGDETAILID        
        
		end        
		else        
		begin        
			INSERT INTO CLOUD_STOCKCOUNTINGDETAIL(STOCKCOUNTINGID,ITEMPRICEID,QUANTITY,WEIGHTINKGS,CREATEDDATE)            
			SELECT @STOCKCOUNTINGID,@ITEMPRICEID,@QUANTITY,@WEIGHTINKGS, GETUTCDATE() + '05:30'      
            
			SET @STOCKCOUNTINGDETAILID = SCOPE_IDENTITY()            
		end        
	END            
            
	SELECT @STOCKCOUNTINGDETAILID            
            
END
