CREATE   PROCEDURE [dbo].[USP_R_POS_RELEASEMANAGEMENT]
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @AppVersion NVARCHAR(50);
    DECLARE @DBVersion NVARCHAR(50);

    SELECT @AppVersion = LTRIM(RTRIM(CONFIGVALUE))
    FROM dbo.TBLCONFIG
    WHERE CONFIGNAME = 'AppVersion';

    SELECT @DBVersion = LTRIM(RTRIM(CONFIGVALUE))
    FROM dbo.TBLCONFIG
    WHERE CONFIGNAME = 'DBVersion';

    SELECT
        AppVersion = @AppVersion,
        DBVersion = @DBVersion;

    SELECT
        BC.COUNTERID,
        B.BRANCHNAME,
        B.BRANCHCODE,
        BC.COUNTERNAME,
        CASE WHEN ISNULL(BC.ISMOBILECOUNTER, 0) = 0 THEN 'POS' ELSE 'MOBILE' END AS COUNTERTYPE,
        BC.APPVERSION AS INSTALLEDAPPVERSION,
        BC.DBVERSION AS INSTALLEDDBVERSION,
        BC.TARGETAPPVERSION,
        BC.TARGETDBVERSION,
        BC.BUILDRELEASEDATE,
        BC.LASTVERSIONCHECK,
        CASE
            WHEN ISNULL(BC.APPVERSION, '') = ISNULL(BC.TARGETAPPVERSION, '')
             AND ISNULL(BC.DBVERSION, '') = ISNULL(BC.TARGETDBVERSION, '')
            THEN 'Yes' ELSE 'No'
        END AS INSTALLEDTARGETMATCH,
        CASE
            WHEN ISNULL(BC.APPVERSION, '') = ISNULL(@AppVersion, '')
             AND ISNULL(BC.DBVERSION, '') = ISNULL(@DBVersion, '')
            THEN 'Yes' ELSE 'No'
        END AS LATESTINSTALLEDMATCH,
        CASE
            WHEN ISNULL(BC.TARGETAPPVERSION, '') = ISNULL(@AppVersion, '')
             AND ISNULL(BC.TARGETDBVERSION, '') = ISNULL(@DBVersion, '')
            THEN 'Yes' ELSE 'No'
        END AS LATESTTARGETMATCH
    FROM dbo.BRANCHCOUNTER BC
    INNER JOIN dbo.BRANCH B ON B.BRANCHID = BC.BRANCHID
    WHERE BC.DELETEDDATE IS NULL
      AND B.DELETEDDATE IS NULL
    ORDER BY B.BRANCHNAME, BC.COUNTERNAME;
END
