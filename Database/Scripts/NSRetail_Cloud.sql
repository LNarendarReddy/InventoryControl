CREATE PROCEDURE [dbo].[USP_CU_BRANCHCOUNTERMOP]
    @Mappings dbo.WH_BRANCHCOUNTERMOPTYPE READONLY
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SET ANSI_PADDING ON;
    SET ANSI_WARNINGS ON;
    SET ARITHABORT ON;
    SET CONCAT_NULL_YIELDS_NULL ON;
    SET NUMERIC_ROUNDABORT OFF;
    BEGIN TRY
        BEGIN TRANSACTION;
        DECLARE @Now datetime = DATEADD(MINUTE, 330, GETUTCDATE());
        -- Apply tombstones before inserting replacement assignments for the same counter/MOP.
        UPDATE T SET COUNTERID = S.COUNTERID, MOPID = S.MOPID,
            PAYMENTGATEWAYINFOID = S.PAYMENTGATEWAYINFOID,
            PAYMENTGATEWAYADDITIONALCONFIG = S.PAYMENTGATEWAYADDITIONALCONFIG,
            CREATEDBY = S.CREATEDBY, CREATEDDATE = S.CREATEDDATE,
            UPDATEDBY = S.UPDATEDBY, UPDATEDDATE = S.UPDATEDDATE,
            DELETEDBY = S.DELETEDBY, DELETEDDATE = S.DELETEDDATE, SYNCDATE = @Now
        FROM dbo.BRANCHCOUNTERMOP T WITH (UPDLOCK, HOLDLOCK)
        INNER JOIN @Mappings S ON S.BRANCHCOUNTERMOPID = T.BRANCHCOUNTERMOPID;

        INSERT dbo.BRANCHCOUNTERMOP
            (BRANCHCOUNTERMOPID, COUNTERID, MOPID, PAYMENTGATEWAYINFOID, PAYMENTGATEWAYADDITIONALCONFIG,
             CREATEDBY, CREATEDDATE, UPDATEDBY, UPDATEDDATE, DELETEDBY, DELETEDDATE, SYNCDATE)
        SELECT BRANCHCOUNTERMOPID, COUNTERID, MOPID, PAYMENTGATEWAYINFOID, PAYMENTGATEWAYADDITIONALCONFIG,
            CREATEDBY, CREATEDDATE, UPDATEDBY, UPDATEDDATE, DELETEDBY, DELETEDDATE, @Now
        FROM @Mappings S
        WHERE NOT EXISTS (SELECT 1 FROM dbo.BRANCHCOUNTERMOP T WITH (UPDLOCK, HOLDLOCK)
                          WHERE T.BRANCHCOUNTERMOPID = S.BRANCHCOUNTERMOPID);
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH;
END
