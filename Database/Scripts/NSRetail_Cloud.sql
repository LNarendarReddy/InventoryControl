CREATE PROCEDURE [dbo].[POS_USP_CU_DAYCLOSURE]              
@BRANCHCOUNTERID INT,              
@dtDenomination POS_BILLMOPVALUES readonly,              
@dtMOP POS_BILLMOPVALUES readonly,              
@RefundAmount decimal(10,2),          
@USERID INT          
, @DaySequenceID INT      
AS              
BEGIN     

	DECLARE  @DAYCLOSUREID INT,@OpeningBalance decimal(18,2),              
	@ClosingBalance decimal(18,2), @BillCount INT, @BillDetailCount INT, @CRefundCount INT   , @DayClosureDetailID INT           
              
	select @OpeningBalance =   ISNULL(SUM(MOPVALUE),0) from POS_BILLMOPDETAIL BM              
	WHERE BM.COUNTERID = @BRANCHCOUNTERID AND BM.DAYCLOSUREID IS NULL  
              
	SELECT @ClosingBalance = ISNULL(SUM(MOPVALUE),0) FROM @dtDenomination  
	SELECT @ClosingBalance = @ClosingBalance +  ISNULL(SUM(MOPVALUE),0) FROM @dtMOP              

	SELECT @DAYCLOSUREID = ISNULL(RUNNINGDAYCLOSUREID,0) + 1 FROM BRANCHCOUNTER WHERE COUNTERID = @BRANCHCOUNTERID
              
	INSERT INTO POS_DAYCLOSURE(BRANCHCOUNTERID,DAYCLOSUREID,OPENINGBALANCE,              
		CLOSINGBALANCE,CLOSINGDIFFERENCE,REFUNDAMOUNT,CLOSUREDATE,CLOSEDBY,      
		CREATEDDATE, SYNCDATE)      
	SELECT   
	@BRANCHCOUNTERID  
	, @DAYCLOSUREID
	,@OpeningBalance  
	,@ClosingBalance  
	,@OpeningBalance - ISNULL(@RefundAmount,0) - @ClosingBalance  
	,ISNULL(@RefundAmount,0)
	,GETDATE()  
	,@USERID  
	,GETDATE(), GETDATE()      

	UPDATE BRANCHCOUNTER SET RUNNINGDAYCLOSUREID = @DAYCLOSUREID WHERE COUNTERID = @BRANCHCOUNTERID

	SELECT @DayClosureDetailID = ISNULL(RUNNINGDAYCLOSUREDETAILID,0) + 1 FROM BRANCHCOUNTER WHERE COUNTERID = @BRANCHCOUNTERID

	CREATE TABLE #DCDETAIL(DCDETAILID INT IDENTITY(1,1) NOT NULL, DAYCLOSUREID INT,DENOMINATIONID INT, MOPID INT,CLOSUREVALUE DECIMAL(18,2),CREATEDDATE DATETIME)
              
	INSERT INTO #DCDETAIL(DAYCLOSUREID,DENOMINATIONID, MOPID,CLOSUREVALUE,CREATEDDATE)      
	SELECT @DAYCLOSUREID,MOPID, NULL,ISNULL(MOPVALUE,0),GETDATE() FROM @dtDenomination              
              
	INSERT INTO #DCDETAIL(DAYCLOSUREID,DENOMINATIONID, MOPID,CLOSUREVALUE,CREATEDDATE)              
	SELECT @DAYCLOSUREID,NULL, MOPID,ISNULL(MOPVALUE,0),GETDATE() FROM @dtMOP              

	INSERT INTO POS_DAYCLOSUREDETAIL(DAYCLOSUREID,DAYCLOSUREDETAILID,DENOMINATIONID, MOPID,CLOSUREVALUE,CREATEDDATE, COUNTERID, SYNCDATE  )              
	SELECT @DAYCLOSUREID,DCDETAILID + @DayClosureDetailID,DENOMINATIONID, MOPID,ISNULL(CLOSUREVALUE,0),GETDATE(), @BRANCHCOUNTERID, GETDATE() FROM #DCDETAIL

	DECLARE @DCDID INT
	SELECT @DCDID = MAX(DCDETAILID) FROM #DCDETAIL

	UPDATE BRANCHCOUNTER SET RUNNINGDAYCLOSUREDETAILID = @DayClosureDetailID + @DCDID WHERE COUNTERID = @BRANCHCOUNTERID
              
	UPDATE POS_BILL SET DAYCLOSUREID = @DAYCLOSUREID,      
	UPDATEDDATE = GETDATE(), UPDATEDBY = @USERID, SYNCDATE = GETDATE()      
	WHERE BRANCHCOUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID IS NULL    

	SET @BillCount = @@ROWCOUNT

	UPDATE POS_BILLDETAIL 
	SET DAYCLOSUREID = @DAYCLOSUREID,      
		UPDATEDDATE = GETDATE(), SYNCDATE = GETDATE()           
	WHERE BRANCHCOUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID IS NULL    
    
	SET @BillDetailCount = @@ROWCOUNT

	UPDATE POS_BILLMOPDETAIL SET DAYCLOSUREID = @DAYCLOSUREID,      
	UPDATEDDATE = GETDATE(), SYNCDATE = GETDATE()      
	WHERE COUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID IS NULL    
              
	UPDATE POS_CREFUND SET DAYCLOSUREID = @DAYCLOSUREID,      
	UPDATEDDATE   = GETDATE(),      
	UPDATEDBY = @USERID, SYNCDATE = GETDATE()      
	WHERE COUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID IS NULL      

	SET @CRefundCount = @@ROWCOUNT
         
	UPDATE POS_DAYSEQUENCE SET ISCLOSED = 1, UPDATEDATE = GETDATE(), SYNCDATE = GETDATE() 
	WHERE BRANCHCOUNTERID = @BRANCHCOUNTERID AND DAYSEQUENCEID = @DaySequenceID

	UPDATE POS_DAYCLOSURE
	SET BILLCOUNT = @BillCount, BILLDETAILCOUNT = @BillDetailCount, CREFUNDCOUNT = @CRefundCount, SYNCDATE = GETDATE()
	WHERE BRANCHCOUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID = @DAYCLOSUREID

	-- delete open bill items 
	UPDATE PBD
	SET PBD.DELETEDDATE = GETDATE(), SYNCDATE = GETDATE()
	FROM
		POS_BILLDETAIL PBD
		INNER JOIN POS_BILL PB ON PB.BRANCHCOUNTERID = PBD.BRANCHCOUNTERID AND PB.BILLID = PBD.BILLID
	WHERE 
		PB.BRANCHCOUNTERID = @BRANCHCOUNTERID 
		AND PB.DAYCLOSUREID = @DAYCLOSUREID 
		AND PBD.DELETEDDATE IS NULL 
		AND PB.BILLSTATUS IN (0, 2)

	SELECT @DAYCLOSUREID    
      
END
