CREATE PROCEDURE [dbo].[POS_USP_RPT_DAYCLOSURE]        
@DAYCLOSUREID INT      ,
@BRANCHCOUNTERID INT
AS        
BEGIN        

	DECLARE @REFUNDAMOUNT DECIMAL(10,2) = 0, @COMPLETEDBILLS INT = 0, @DRAFTBILLS INT = 0, @VOIDITEMS INT = 0      

	SELECT @REFUNDAMOUNT = REFUNDAMOUNT 
	FROM POS_DAYCLOSURE 
	WHERE BRANCHCOUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID = @DAYCLOSUREID

	SELECT @VOIDITEMS = COUNT(*)      
	FROM POS_BILLDETAIL       
	WHERE BRANCHCOUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID = @DAYCLOSUREID AND DELETEDDATE IS NOT NULL      
      
	SELECT @COMPLETEDBILLS = COUNT(*) FROM POS_BILL       
	WHERE BRANCHCOUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID = @DAYCLOSUREID AND BILLSTATUS = 1      
      
	SELECT @DRAFTBILLS = COUNT(*) FROM POS_BILL       
	WHERE BRANCHCOUNTERID = @BRANCHCOUNTERID AND DAYCLOSUREID = @DAYCLOSUREID AND BILLSTATUS = 2   

