CREATE PROCEDURE [dbo].[POS_USP_R_LOAD]        
@UserID INT, @BranchCounterID INT        
AS        
BEGIN        
	DECLARE @DaySequenceID INT        
        
	SELECT TOP 1 @DaySequenceID = DAYSEQUENCEID FROM POS_DAYSEQUENCE WHERE BRANCHCOUNTERID = @BranchCounterID ORDER BY OPENDATE DESC         
        
	IF ISNULL(@DaySequenceID, 0) = 0 OR (SELECT OPENDATE FROM POS_DAYSEQUENCE WHERE DAYSEQUENCEID = @DaySequenceID AND BRANCHCOUNTERID = @BranchCounterID) <> CAST(GETDATE() AS DATE)        
	BEGIN        
		SELECT @DaySequenceID = ISNULL(RUNNINGDAYSEQUENCEID,0) + 1 FROM BRANCHCOUNTER WHERE COUNTERID = @BranchCounterID
		INSERT INTO POS_DAYSEQUENCE(DAYSEQUENCEID, OPENDATE, BRANCHCOUNTERID, CREATEDATE)        
		SELECT @DaySequenceID, CAST(GETDATE() AS DATE), @BranchCounterID, GETDATE()        

		UPDATE BRANCHCOUNTER SET RUNNINGDAYSEQUENCEID = @DaySequenceID WHERE COUNTERID = @BranchCounterID
	END        
	ELSE IF (SELECT ISCLOSED FROM POS_DAYSEQUENCE WHERE DAYSEQUENCEID = @DaySequenceID AND BRANCHCOUNTERID = @BranchCounterID) = 1
	BEGIN         
		SELECT 'Billing closed'        
		RETURN        
	END        
        
	DECLARE @LastBillNum VARCHAR(30)        
	SELECT @LastBillNum = LASTUSEDBILLNUM FROM POS_DAYSEQUENCE WHERE BRANCHCOUNTERID = @BranchCounterID AND DAYSEQUENCEID = @DaySequenceID        
        
	IF ISNULL(@LastBillNum, '') = ''
	BEGIN        
		SELECT @LastBillNum = BC.COUNTERNAME  + '/' + FORMAT(GETDATE(), 'yyyyMMdd') + '/0000'        
		FROM BRANCHCOUNTER BC WHERE BC.COUNTERID = @BranchCounterID      
        
		UPDATE POS_DAYSEQUENCE        
		SET LASTUSEDBILLNUM = @LastBillNum,
		UPDATEDATE = GETDATE()
		WHERE BRANCHCOUNTERID = @BranchCounterID AND DAYSEQUENCEID = @DaySequenceID
	END        
         
	SELECT @BranchCounterID AS BRANCHCOUNTERID, @DaySequenceID AS DAYSEQUENCEID
	EXEC POS_USP_R_GETNEXTBILL @UserID, @DaySequenceID,@BranchCounterID
      
END
