CREATE PROCEDURE [dbo].[POS_USP_D_BILLDETAIL]  
@BillDetailID int  
, @UserID int  
, @SNos POS_BILLDETAILSNO READONLY  
, @BranchCounterID INT
, @BRANCHID INT
AS  
BEGIN  
	UPDATE POS_BILLDETAIL  
	SET DELETEDDATE = GETDATE(), SYNCDATE = GETDATE()  
	WHERE BRANCHCOUNTERID = @BranchCounterID
		AND BILLDETAILID = @BillDetailID  

  
	UPDATE BD  
	SET SNO = SNOS.SNO, SYNCDATE = GETDATE()    
	FROM  POS_BILLDETAIL BD   
	INNER JOIN @SNos SNOS ON SNOS.BILLDETAILID = BD.BILLDETAILID  
	WHERE BD.BRANCHCOUNTERID = @BranchCounterID
  
	DECLARE @OfferID INT, @DealID INT, @OfferAppliesToID INT, @DealAppliesToID INT, @ItemPriceID INT  
	, @BillID INT, @DealTypeID INT
  
	SELECT @ItemPriceID = ITEMPRICEID, @BillID = BILLID  
	FROM POS_BILLDETAIL WhERE BRANCHCOUNTERID = @BranchCounterID AND BILLDETAILID = @BillDetailID  
  
	SELECT @OfferID = OFFERID, @OfferAppliesToID = OFFERAPPLIESTOID, @DealID = DEALID, @DealAppliesToID = DEALAPPLIESTOID  
	FROM UDF_GETOFFERS(@ItemPriceID,0, @BRANCHID)  
  
	CREATE TABLE #BilledGroupItems(BRANCHCOUNTERID INT,BILLDETAILID INT, TOTALQUANTITY INT, MRPQUANTITY INT, SALEPRICEQUANTITY INT, FREEQUANTITY INT)  

	SELECT @DealTypeID = OFFERTYPEID FROM OFFER WHERE OFFERID = @DealID AND ISNULL(@DealID,0) > 0

  
	IF (@DealTypeID = 4 OR @DealTypeID = 5) AND @DealAppliesToID >= 2
	BEGIN  
    
	DECLARE @MRPQuantity INT, @FreeQuantity INT, @SalePriceQuantity INT, @DealQuantity INT  
  
	SELECT @DealQuantity = OFRTYP.BUYQUANTITY + OFRTYP.FREEQUANTITY   
	FROM   
	OFFER OFR  
	INNER JOIN OFFERTYPE OFRTYP ON OFRTYP.OFFERTYPEID = OFR.OFFERTYPEID  
	WHERE  
	OFR.OFFERID = @DealID  
  
  
	INSERT INTO #BilledGroupItems  
	SELECT BD.BRANCHCOUNTERID, BD.BILLDETAILID, BD.QUANTITY AS TOTALQUANTITY, 0 AS MRPQUANTITY, 0 AS SALEPRICEQUANTITY, 0 AS FREEQUANTITY   
	FROM  
	POS_BILLDETAIL BD  
	INNER JOIN ITEMPRICE IP ON IP.ITEMPRICEID = BD.ITEMPRICEID  
	INNER JOIN OFFERITEMMAP OFRITM ON OFRITM.ITEMCODEID = IP.ITEMCODEID
	WHERE  
	BD.BRANCHCOUNTERID = @BranchCounterID
	AND BD.BILLID = @BillID  
	AND BD.DELETEDDATE IS NULL  
	AND OFRITM.OFFERID = @DealID  
  
	DEClARE @BuyQuantity INT  
	SELECT @BuyQuantity = SUM(TOTALQUANTITY) FROM #BilledGroupItems  
     
	SELECT @MRPQuantity = (@BuyQuantity / (OFRTYPE.BUYQUANTITY + OFRTYPE.FREEQUANTITY)) * OFRTYPE.BUYQUANTITY  
	, @FreeQuantity = (@BuyQuantity / (OFRTYPE.BUYQUANTITY + OFRTYPE.FREEQUANTITY)) * OFRTYPE.FREEQUANTITY  
	, @SalePriceQuantity = (@BuyQuantity % (OFRTYPE.BUYQUANTITY + OFRTYPE.FREEQUANTITY))  
	FROM  OFFER OFR  
	INNER JOIN OFFERTYPE OFRTYPE ON OFRTYPE.OFFERTYPEID = OFR.OFFERTYPEID  
	WHERE OFR.OFFERID = @DealID  
          
	-- Find lowest MRP items to give as free  
	WHILE @FreeQuantity > 0  
	BEGIN  
	DECLARE @CurBillDetailID INT, @CurQuantity INT  
  
	SELECT TOP 1 @CurBillDetailID = BGI.BILLDETAILID, @CurQuantity = BGI.TOTALQUANTITY  
	FROM   
	#BilledGroupItems BGI   
	INNER JOIN POS_BILLDETAIL BD ON BD.BRANCHCOUNTERID = BGI.BRANCHCOUNTERID AND BD.BILLDETAILID = BGI.BILLDETAILID  
	INNER JOIN ITEMPRICE IP ON IP.ITEMPRICEID = BD.ITEMPRICEID  
	WHERE BGI.TOTALQUANTITY > 0  
	ORDER BY IP.MRP  
       
	DECLARE @FreeQuantityToupdate INT  
	IF @CurQuantity >= @FreeQuantity  
	BEGIN  
	SELECT @CurQuantity = @CurQuantity - @FreeQuantity, @FreeQuantityToupdate = @FreeQuantity, @FreeQuantity = 0  
	END  
	ELSE  
	BEGIN  
	SELECT @FreeQuantityToupdate = @FreeQuantity - @CurQuantity, @FreeQuantity = @FreeQuantity - @CurQuantity, @CurQuantity = 0  
	END  
  
	UPDATE #BilledGroupItems  
	SET TOTALQUANTITY = @CurQuantity, FREEQUANTITY = @FreeQuantityToupdate  
	WHERE BILLDETAILID = @CurBillDetailID  
	END  
  
	-- Find next lowest MRP items to give as sale price  
	WHILE @SalePriceQuantity > 0  
	BEGIN  
  
	SELECT TOP 1 @CurBillDetailID = BGI.BILLDETAILID, @CurQuantity = BGI.TOTALQUANTITY  
	FROM   
	#BilledGroupItems BGI   
	INNER JOIN POS_BILLDETAIL BD ON BD.BRANCHCOUNTERID = BGI.BRANCHCOUNTERID AND BD.BILLDETAILID = BGI.BILLDETAILID  
	INNER JOIN ITEMPRICE IP ON IP.ITEMPRICEID = BD.ITEMPRICEID  
	WHERE BGI.TOTALQUANTITY > 0  
	ORDER BY IP.MRP  
  
	DECLARE @SalePriceToUpdate INT  
	IF @CurQuantity >= @SalePriceQuantity  
	BEGIN  
	SELECT @CurQuantity = @CurQuantity - @SalePriceQuantity, @SalePriceToUpdate = @SalePriceQuantity, @SalePriceQuantity = 0  
	END  
	ELSE  
	BEGIN  
	SELECT @SalePriceToUpdate = @SalePriceQuantity - @CurQuantity, @SalePriceQuantity = @SalePriceQuantity - @CurQuantity, @CurQuantity = 0  
	END  
  
	UPDATE #BilledGroupItems  
	SET TOTALQUANTITY = @CurQuantity, SALEPRICEQUANTITY = @SalePriceToUpdate  
	WHERE BILLDETAILID = @CurBillDetailID  
	END  
          
	UPDATE #BilledGroupItems  
	SET MRPQUANTITY = TOTALQUANTITY   
  
	-- update quantities and MRP based prices instead of sale prices  
	UPDATE BD  
	SET     
	BD.BILLEDAMOUNT = (BGI.MRPQUANTITY * IP.MRP) + (BGI.SALEPRICEQUANTITY * (IP.MRP - dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(IP.ITEMPRICEID, BGI.SALEPRICEQUANTITY, @BRANCHID), IP.ITEMPRICEID)))  
	, BD.DISCOUNT = (BGI.FREEQUANTITY * IP.MRP) + (BGI.SALEPRICEQUANTITY * dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(IP.ITEMPRICEID, BGI.SALEPRICEQUANTITY,@BRANCHID), IP.ITEMPRICEID))  
	, BD.OFFERID = CASE WHEN @BuyQuantity / @DealQuantity > 0 THEN @DealID ELSE @OfferID END, SYNCDATE = GETDATE()    
	FROM  
	POS_BILLDETAIL BD  
	INNER JOIN #BilledGroupItems BGI ON BGI.BRANCHCOUNTERID = BD.BRANCHCOUNTERID AND BGI.BILLDETAILID = BD.BILLDETAILID  
	INNER JOIN ITEMPRICE IP ON IP.ITEMPRICEID = BD.ITEMPRICEID  
  
 
	END  
	ELSE
 
	DECLARE @BuyDealID INT = 0
	SELECT @BuyDealID = OFFERID FROM POS_BILLDETAIL WHERE BILLDETAILID = @BillDetailID

	IF EXISTS (SELECT 1 FROM OFFER WHERE OFFERID = @BuyDealID AND OFFERTYPEID = 1006)
	BEGIN
	
	INSERT INTO #BilledGroupItems(BRANCHCOUNTERID, BILLDETAILID)
	SELECT BRANCHCOUNTERID, BILLDETAILID FROM POS_BILLDETAIL PBD
	WHERE PBD.BRANCHCOUNTERID = @BranchCounterID AND PBD.BILLID = @BillID AND PBD.OFFERID = @BuyDealID AND PBD.DELETEDDATE IS NULL

	UPDATE PBD
	SET 
	PBD.BILLEDAMOUNT = (PBD.QUANTITY * (IP.MRP - dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(IP.ITEMPRICEID, PBD.QUANTITY, @BRANCHID), IP.ITEMPRICEID)))
	, PBD.DISCOUNT = (PBD.QUANTITY * dbo.UDF_GET_DISCOUNTVALUE(dbo.UDF_GETOFFER(IP.ITEMPRICEID, PBD.QUANTITY,@BRANCHID), IP.ITEMPRICEID))
	, PBD.OFFERID = dbo.UDF_GETOFFER(IP.ITEMPRICEID, PBD.QUANTITY,@BRANCHID), SYNCDATE = GETDATE()  
	FROM POS_BILLDETAIL PBD
	INNER JOIN #BilledGroupItems BGI ON PBD.BRANCHCOUNTERID = BGI.BRANCHCOUNTERID AND PBD.BILLDETAILID = BGI.BILLDETAILID
	INNER JOIN ITEMPRICE IP ON IP.ITEMPRICEID = PBD.ITEMPRICEID

	END
  
	-- recalculate GST in case of offer or deals  
	UPDATE BD  
	SET   
	BD.CGST = ROUND((BD.BILLEDAMOUNT * GST.CGST) / 100, 2)  
	, BD.SGST = ROUND((BD.BILLEDAMOUNT * GST.SGST) / 100, 2)  
	, BD.IGST = ROUND((BD.BILLEDAMOUNT * GST.IGST) / 100, 2)  
	, BD.CESS = ROUND((BD.BILLEDAMOUNT * GST.CESS) / 100, 2)  
	, BD.GSTVALUE = ROUND((BD.BILLEDAMOUNT * (GST.CGST + GST.SGST + GST.IGST + GST.CESS)) / 100, 2) , SYNCDATE = GETDATE()   
	FROM  
	POS_BILLDETAIL BD  
	INNER JOIN #BilledGroupItems BGI ON BGI.BRANCHCOUNTERID = BD.BRANCHCOUNTERID AND BGI.BILLDETAILID = BD.BILLDETAILID  
	INNER JOIN GSTDETAIL GST ON GST.GSTID = BD.GSTID  
	
	EXEC POS_USP_R_BILL @BILLID, 0, @BranchCounterID
END 
