CREATE FUNCTION [dbo].[UDF_GET_DISCOUNTVALUE](@OfferID INT = 0, @ItemPriceID INT) RETURNS DECIMAL(10, 2) AS
BEGIN
	DECLARE @MRP DECIMAL(10, 2), @DiscountValue DECIMAL(10, 2), @OfferTypeCode VARCHAR(10)
	
	IF ISNULL(@OfferID, 0) = 0
	BEGIN
		SELECT @DiscountValue = MRP - SALEPRICE
		FROM ITEMPRICE
		WHERE ITEMPRICEID = @ItemPriceID

		RETURN @DiscountValue
	END

	SELECT @OfferTypeCode = OFRTYP.OFFERTYPECODE
	FROM 
		OFFER OFR 
		INNER JOIN OFFERTYPE OFRTYP ON OFRTYP.OFFERTYPEID = OFR.OFFERTYPEID
	WHERE OFR.OFFERID = @OfferID

	SELECT @MRP = MRP
	FROM ITEMPRICE
	WHERE ITEMPRICEID = @ItemPriceID

	IF @OfferTypeCode = 'DF'
	BEGIN
		SELECT @DiscountValue = OFFERVALUE FROM OFFER WHERE OFFERID = @OfferID
	END
	ELSE IF @OfferTypeCode = 'DP'
	BEGIN
		SELECT @DiscountValue = ((OFFERVALUE * @MRP) / 100) FROM OFFER WHERE OFFERID = @OfferID
	END
	ELSE IF @OfferTypeCode = 'FR'
	BEGIN
		SELECT @DiscountValue = (@MRP - OFFERVALUE) FROM OFFER WHERE OFFERID = @OfferID
	END

	RETURN @DiscountValue
END
GO
