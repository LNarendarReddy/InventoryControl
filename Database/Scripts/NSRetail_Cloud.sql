CREATE PROC [dbo].[USP_RPT_INSTALLEDVERSION]
AS
BEGIN

	DECLARE @AppVersion nvarchar(50), @DBVersion nvarchar(50)
	
	SELECT @AppVersion = CONFIGVALUE FROM TBLCONFIG where CONFIGNAME = 'AppVersion'
	SELECT @DBVersion = CONFIGVALUE FROM TBLCONFIG where CONFIGNAME = 'DBVersion'

	SELECT 
		B.BRANCHNAME, 
		B.BRANCHCODE, 
		BC.COUNTERNAME,
		CASE WHEN ISNULL(BC.ISMOBILECOUNTER,0) = 0 THEN 'POS' ELSE 'MOBILE' END AS [Counter Type], 
		BC.APPVERSION, 
		BC.DBVERSION, 
		BC.LASTVERSIONCHECK, 
		CASE WHEN BC.APPVERSION = @AppVersion AND BC.DBVERSION = @DBVersion THEN 'Yes' ELSE 'No' END AS ISUPTODATE
	FROM
		BRANCHCOUNTER BC
		INNER JOIN BRANCH B ON B.BRANCHID = BC.BRANCHID
	WHERE BC.DELETEDDATE IS NULL AND B.DELETEDDATE IS NULL 
	ORDER BY 1, 3
END
