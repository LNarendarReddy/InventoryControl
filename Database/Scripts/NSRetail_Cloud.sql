            I.UQCID = S.UQCID,
            I.HSNCODE = S.HSNCODE,
            I.GSTID = S.GSTID,
            I.VENDORSKUCODE = S.VENDORSKUCODE,
            I.SEASONALITYIDS = S.SEASONALITYIDS,
            I.REFUNDPATHID = S.REFUNDPATHID,
            I.ISDSD = S.ISDSD,
            I.INNERCASEQTY = S.INNERCASEQTY,
            I.OUTERCASEQTY = S.OUTERCASEQTY,
            I.PRODUCTRANK = S.PRODUCTRANK,
            I.SUPPLIERINDENTITEMTYPEID = S.SUPPLIERINDENTITEMTYPEID
        FROM dbo.ITEM AS I WITH (UPDLOCK, HOLDLOCK)
        INNER JOIN @Items AS S ON S.ITEMID = I.ITEMID;

        INSERT INTO dbo.ITEM
        (
            ITEMID, SKUCODE, ITEMNAME, CREATEDDATE, UPDATEDATE,
            DELETEDDATE, ISOPENITEM, PARENTITEMID, UOMID,
            CATEGORYID, SYNCDATE,
            -- New columns appended.
            DESCRIPTION, CREATEDBY, UPDATEDBY, DELETEDBY,
            SUBCATEGORYID, CLASSIFICATIONID, SUBCLASSIFICATIONID,
            BRANDID, MANUFACTURERID, UQCID, HSNCODE, GSTID,
            VENDORSKUCODE, SEASONALITYIDS, REFUNDPATHID, ISDSD,
            INNERCASEQTY, OUTERCASEQTY, PRODUCTRANK,
            SUPPLIERINDENTITEMTYPEID
        )
        SELECT
            S.ITEMID, S.SKUCODE, S.ITEMNAME, S.CREATEDDATE,
