CREATE PROCEDURE [dbo].[CLOUD_USP_CU_STOCKCOUNTING]    
@STOCKCOUNTINGID INT = 0,    
@BRANCHID INT,    
@USERID INT,
@CREATEDDATE DATETIME,
@STOCKLOCATIONNAME NVARCHAR(100) = ''
AS    
BEGIN    

	IF NOT EXISTS(SELECT 1 FROM BRANCH WHERE BRANCHID = @BRANCHID AND ISNULL(ENABLESTOCKCOUNTING,0) = 1)
	BEGIN
		SELECT 'Stock counting not enabled for selected branch, please contact your administrator.'
		return;
	END



	SELECT @STOCKCOUNTINGID  = ISNULL(STOCKCOUNTINGID,0) FROM CLOUD_STOCKCOUNTING 
	WHERE BRANCHID = @BRANCHID AND CREATEDBY = @USERID AND DELETEDBY IS NULL AND ISNULL(STATUS,0) = 0

	IF(@STOCKCOUNTINGID = 0)
	BEGIN

		DECLARE @STOCKLOCATIONID INT = 0
		SELECT @STOCKLOCATIONID = ISNULL(STOCKLOCATIONID,0) FROM STOCKLOCATION 
		WHERE BRANCHID = @BRANCHID AND STOCKLOCATIONNAME = @STOCKLOCATIONNAME
		IF(@STOCKLOCATIONID = 0 )
		BEGIN
			INSERT INTO STOCKLOCATION(BRANCHID, STOCKLOCATIONNAME, CREATEDBY, CREATEDDATE)
			VALUES (@BRANCHID, @STOCKLOCATIONNAME, @USERID, GETDATE())
			SET @STOCKLOCATIONID = SCOPE_IDENTITY()
		END

		INSERT INTO CLOUD_STOCKCOUNTING (BRANCHID,CREATEDBY,CREATEDDATE, STATUS, STOCKLOCATIONID)    
		SELECT @BRANCHID,@USERID, GETUTCDATE() + '05:30',0, @STOCKLOCATIONID
		SET @STOCKCOUNTINGID = SCOPE_IDENTITY()    
	END
    
	SELECT @STOCKCOUNTINGID    

END
