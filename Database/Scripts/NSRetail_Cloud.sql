AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @SyncDate datetime = DATEADD(MINUTE, 330, GETUTCDATE());

    BEGIN TRY
        BEGIN TRANSACTION;

        UPDATE I
        SET I.SKUCODE = S.SKUCODE,
            I.ITEMNAME = S.ITEMNAME,
            I.CREATEDDATE = S.CREATEDDATE,
            I.UPDATEDATE = S.UPDATEDATE,
            I.DELETEDDATE = S.DELETEDDATE,
            I.ISOPENITEM = S.ISOPENITEM,
            I.PARENTITEMID = S.PARENTITEMID,
            I.UOMID = S.UOMID,
            I.CATEGORYID = S.CATEGORYID,
            I.SYNCDATE = @SyncDate,
            -- New assignments appended.
            I.DESCRIPTION = S.DESCRIPTION,
            I.CREATEDBY = S.CREATEDBY,
            I.UPDATEDBY = S.UPDATEDBY,
            I.DELETEDBY = S.DELETEDBY,
            I.SUBCATEGORYID = S.SUBCATEGORYID,
            I.CLASSIFICATIONID = S.CLASSIFICATIONID,
            I.SUBCLASSIFICATIONID = S.SUBCLASSIFICATIONID,
            I.BRANDID = S.BRANDID,
