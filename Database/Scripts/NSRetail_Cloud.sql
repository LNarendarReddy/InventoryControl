create PROCEDURE [dbo].[POS_USP_R_BILL]                                 
 @BillID INT,                     
 @DaySequenceID INT                                ,
 @BranchCounterID INT
AS                                
BEGIN                                
                                
	 DECLARE @LastBillID INT                                
	 SELECT @LastBillID = LASTBILLID FROM POS_DAYSEQUENCE WHERE BRANCHCOUNTERID = @BranchCounterID AND DAYSEQUENCEID = @DaySequenceID
                                
	 DECLARE @LastBilledAmount DECIMAL(11, 2)                                
