	FROM POS_DAYSEQUENCE DS
		INNER JOIN POS_BILL PB ON PB.BRANCHCOUNTERID = DS.BRANCHCOUNTERID AND  PB.BILLID = DS.OPENBILLID 
	WHERE DAYSEQUENCEID = @DaySequenceID AND DS.BRANCHCOUNTERID = @BranchCounterID

